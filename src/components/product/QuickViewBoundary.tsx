import { Component, type ReactNode } from "react";

/** Keep an unavailable lazy chunk inside the dialog, with close and details usable. */
export class QuickViewBoundary extends Component<
  { children: ReactNode; fallback: ReactNode },
  { failed: boolean }
> {
  state = { failed: false };

  static getDerivedStateFromError() {
    return { failed: true };
  }

  render() {
    return this.state.failed ? this.props.fallback : this.props.children;
  }
}
